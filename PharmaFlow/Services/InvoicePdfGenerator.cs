using System.Globalization;
using System.Text;
using PharmaFlow.Models;

namespace PharmaFlow.Services;

/// <summary>
/// Generates a self-contained PDF receipt without relying on a third-party PDF service.
/// Uses the built-in PDF Helvetica fonts so the document can be generated offline.
/// Non-Latin characters are safely normalized for those standard fonts.
/// </summary>
public static class InvoicePdfGenerator
{
    private const double PageWidth = 595;
    private const double PageHeight = 842;
    private static readonly CultureInfo IndiaCulture = CultureInfo.GetCultureInfo("en-IN");

    public static byte[] Generate(
        SalesBill bill,
        IReadOnlyList<SalesBillItem> items,
        string businessName,
        string? businessPhone,
        string? businessEmail)
    {
        var pages = new List<string>();
        var commands = new List<string>();
        var rowY = 0d;

        void Text(double x, double y, string? value, int size = 9, bool bold = false)
        {
            var safeText = EscapePdfText(ToPdfText(value));
            commands.Add($"BT /{(bold ? "F2" : "F1")} {size} Tf 1 0 0 1 {Number(x)} {Number(y)} Tm ({safeText}) Tj ET");
        }

        void Line(double x1, double y1, double x2, double y2)
        {
            commands.Add($"q 0.82 0.86 0.90 RG 0.7 w {Number(x1)} {Number(y1)} m {Number(x2)} {Number(y2)} l S Q");
        }

        void FillRect(double x, double y, double width, double height, double r, double g, double b)
        {
            commands.Add($"q {Number(r)} {Number(g)} {Number(b)} rg {Number(x)} {Number(y)} {Number(width)} {Number(height)} re f Q");
        }

        void StartPage(int pageNumber, bool firstPage)
        {
            commands.Clear();
            FillRect(32, 754, 531, 58, 0.91, 0.96, 0.97);
            Text(46, 788, Limit(businessName, 43), 16, true);
            Text(46, 771, businessPhone is null ? "Pharmacy invoice" : "Phone: " + businessPhone, 8);
            if (!string.IsNullOrWhiteSpace(businessEmail))
                Text(46, 758, "Email: " + businessEmail, 8);

            Text(446, 789, "INVOICE", 13, true);
            Text(446, 772, "No: " + bill.BillNumber, 8, true);
            Text(446, 758, $"Page {pageNumber}", 8);

            if (firstPage)
            {
                Text(40, 728, "Invoice date & time", 8, true);
                Text(40, 713, bill.CreatedAt.AddHours(5.5).ToString("dd MMM yyyy, hh:mm tt", IndiaCulture), 10);
                Text(300, 728, "Payment method", 8, true);
                Text(300, 713, bill.PaymentMethod, 10, true);

                Text(40, 687, "Customer", 8, true);
                Text(40, 672, string.IsNullOrWhiteSpace(bill.CustomerName) ? "Walk-in customer" : bill.CustomerName, 10);
                Text(300, 687, "Customer phone", 8, true);
                Text(300, 672, string.IsNullOrWhiteSpace(bill.CustomerPhone) ? "Not provided" : bill.CustomerPhone, 10);
                Line(40, 654, 555, 654);
                DrawTableHeader(632);
                rowY = 609;
            }
            else
            {
                Text(40, 730, "Invoice date & time: " + bill.CreatedAt.AddHours(5.5).ToString("dd MMM yyyy, hh:mm tt", IndiaCulture), 8);
                DrawTableHeader(704);
                rowY = 681;
            }
        }

        void DrawTableHeader(double y)
        {
            FillRect(36, y - 8, 523, 24, 0.91, 0.94, 0.96);
            Text(43, y, "PRODUCT", 7, true);
            Text(239, y, "BATCH", 7, true);
            Text(323, y, "QTY", 7, true);
            Text(363, y, "RATE (INR)", 7, true);
            Text(435, y, "GST", 7, true);
            Text(483, y, "AMOUNT (INR)", 7, true);
        }

        void FinishPage()
        {
            Text(40, 32, "Generated by PharmaFlow", 7);
            Text(447, 32, "Thank you!", 7, true);
            pages.Add(string.Join("\n", commands));
        }

        StartPage(1, true);

        foreach (var item in items)
        {
            if (rowY < 145)
            {
                FinishPage();
                StartPage(pages.Count + 1, false);
            }

            Text(43, rowY, Limit(item.ProductName, 32), 8, true);
            Text(239, rowY, Limit(item.BatchNumber, 14), 7);
            Text(323, rowY, item.Quantity.ToString("0.##", CultureInfo.InvariantCulture), 8);
            Text(363, rowY, item.UnitPrice.ToString("0.00", IndiaCulture), 7);
            Text(435, rowY, item.GstRate.ToString("0.##", CultureInfo.InvariantCulture) + "%", 7);
            Text(483, rowY, item.LineTotal.ToString("0.00", IndiaCulture), 7);
            Line(40, rowY - 9, 555, rowY - 9);
            rowY -= 23;
        }

        if (rowY < 238)
        {
            FinishPage();
            StartPage(pages.Count + 1, false);
            rowY = 650;
        }

        var totalsY = rowY - 4;
        Text(365, totalsY, "Subtotal", 8);
        Text(475, totalsY, "INR " + bill.Subtotal.ToString("N2", IndiaCulture), 8);
        totalsY -= 18;

        Text(365, totalsY, "Taxable amount", 8);
        Text(475, totalsY, "INR " + bill.TaxableAmount.ToString("N2", IndiaCulture), 8);
        totalsY -= 18;

        if (bill.CgstAmount > 0)
        {
            Text(365, totalsY, "CGST", 8);
            Text(475, totalsY, "INR " + bill.CgstAmount.ToString("N2", IndiaCulture), 8);
            totalsY -= 18;
        }

        if (bill.SgstAmount > 0)
        {
            Text(365, totalsY, "SGST", 8);
            Text(475, totalsY, "INR " + bill.SgstAmount.ToString("N2", IndiaCulture), 8);
            totalsY -= 18;
        }

        if (bill.IgstAmount > 0)
        {
            Text(365, totalsY, "IGST", 8);
            Text(475, totalsY, "INR " + bill.IgstAmount.ToString("N2", IndiaCulture), 8);
            totalsY -= 18;
        }

        if (bill.GstAmount > 0)
        {
            Text(365, totalsY, "Total GST", 8);
            Text(475, totalsY, "INR " + bill.GstAmount.ToString("N2", IndiaCulture), 8);
            totalsY -= 18;
        }

        Line(355, totalsY + 8, 555, totalsY + 8);
        Text(365, totalsY - 10, "TOTAL AMOUNT", 10, true);
        Text(465, totalsY - 10, "INR " + bill.TotalAmount.ToString("N2", IndiaCulture), 10, true);
        totalsY -= 31;
        Text(365, totalsY, "Payment: " + bill.PaymentMethod, 8, true);

        FinishPage();
        return BuildPdf(pages);
    }

    private static byte[] BuildPdf(IReadOnlyList<string> pageContents)
    {
        var objectBodies = new List<byte[]>();
        objectBodies.Add(Encoding.ASCII.GetBytes("<< /Type /Catalog /Pages 2 0 R >>"));

        var kids = new StringBuilder();
        for (var i = 0; i < pageContents.Count; i++)
        {
            if (i > 0) kids.Append(' ');
            kids.Append(5 + (i * 2)).Append(" 0 R");
        }

        objectBodies.Add(Encoding.ASCII.GetBytes(
            $"<< /Type /Pages /Kids [{kids}] /Count {pageContents.Count} >>"));
        objectBodies.Add(Encoding.ASCII.GetBytes(
            "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>"));
        objectBodies.Add(Encoding.ASCII.GetBytes(
            "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>"));

        foreach (var content in pageContents)
        {
            var pageObjectId = 5 + (objectBodies.Count - 4);
            var contentObjectId = pageObjectId + 1;
            objectBodies.Add(Encoding.ASCII.GetBytes(
                $"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {Number(PageWidth)} {Number(PageHeight)}] " +
                $"/Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents {contentObjectId} 0 R >>"));

            var stream = Encoding.ASCII.GetBytes(content);
            using var contentObject = new MemoryStream();
            WriteAscii(contentObject, $"<< /Length {stream.Length} >>\nstream\n");
            contentObject.Write(stream);
            WriteAscii(contentObject, "\nendstream");
            objectBodies.Add(contentObject.ToArray());
        }

        using var output = new MemoryStream();
        WriteAscii(output, "%PDF-1.4\n% PharmaFlow invoice\n");
        var offsets = new List<long> { 0 };

        for (var i = 0; i < objectBodies.Count; i++)
        {
            offsets.Add(output.Position);
            WriteAscii(output, $"{i + 1} 0 obj\n");
            output.Write(objectBodies[i]);
            WriteAscii(output, "\nendobj\n");
        }

        var xrefOffset = output.Position;
        WriteAscii(output, $"xref\n0 {objectBodies.Count + 1}\n");
        WriteAscii(output, "0000000000 65535 f \n");
        foreach (var offset in offsets.Skip(1))
            WriteAscii(output, $"{offset:0000000000} 00000 n \n");

        WriteAscii(output,
            $"trailer\n<< /Size {objectBodies.Count + 1} /Root 1 0 R >>\nstartxref\n{xrefOffset}\n%%EOF");
        return output.ToArray();
    }

    private static string ToPdfText(string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return string.Empty;

        var normalized = value
            .Replace("₹", "INR ", StringComparison.Ordinal)
            .Replace("—", "-", StringComparison.Ordinal)
            .Replace("–", "-", StringComparison.Ordinal)
            .Replace("•", "-", StringComparison.Ordinal)
            .Replace("·", "-", StringComparison.Ordinal)
            .Normalize(NormalizationForm.FormD);

        var result = new StringBuilder(normalized.Length);
        foreach (var character in normalized)
        {
            if (CharUnicodeInfo.GetUnicodeCategory(character) == UnicodeCategory.NonSpacingMark)
                continue;

            if (character is >= ' ' and <= '~')
                result.Append(character);
            else if (character is '\r' or '\n' or '\t')
                result.Append(' ');
            else
                result.Append('?');
        }

        return result.ToString();
    }

    private static string EscapePdfText(string text) =>
        text.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("(", "\\(", StringComparison.Ordinal)
            .Replace(")", "\\)", StringComparison.Ordinal);

    private static string Limit(string? text, int maxLength)
    {
        var value = ToPdfText(text);
        return value.Length <= maxLength ? value : value[..Math.Max(0, maxLength - 3)] + "...";
    }

    private static string Number(double value) =>
        value.ToString("0.##", CultureInfo.InvariantCulture);

    private static void WriteAscii(Stream stream, string value)
    {
        var bytes = Encoding.ASCII.GetBytes(value);
        stream.Write(bytes, 0, bytes.Length);
    }
}
