    const languageToLocale = { en: "en-IN", kn: "kn-IN", hi: "hi-IN" };
    const htmlLang = { en: "en", kn: "kn", hi: "hi" };

    const applyLanguage = (language) => {
        const selected = translations[language] ? language : "en";
        const dictionary = translations[selected];

        document.documentElement.lang = htmlLang[selected];

        document.querySelectorAll("[data-i18n]").forEach(element => {
            const key = element.dataset.i18n;
            if (dictionary[key]) element.textContent = dictionary[key];
        });

        document.querySelectorAll("[data-i18n-message]").forEach(element => {
            const key = element.dataset.i18nMessage;
            if (dictionary[key]) element.textContent = dictionary[key];
        });

        document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
            const key = element.dataset.i18nPlaceholder;
            if (dictionary[key]) element.setAttribute("placeholder", dictionary[key]);
        });

        document.querySelectorAll("[data-i18n-attr]").forEach(element => {
            const pairs = element.dataset.i18nAttr.split(",");
            pairs.forEach(pair => {
                const [attribute, key] = pair.split(":");
                if (attribute && key && dictionary[key]) element.setAttribute(attribute, dictionary[key]);
            });
        });

        const rawTitle = document.querySelector("[data-page-title-key]")?.dataset.pageTitleKey;
        const pageTitleMap = {
            "Dashboard": "dashboard",
            "My Profile": "myProfile",
            "Send Feedback": "sendFeedback",
            "Privacy Policy": "privacyPolicy",
            "Error": "error"
        };
        const titleKey = pageTitleMap[rawTitle];
        if (titleKey && dictionary[titleKey]) {
            document.title = document.title.replace(/^[^-]+/, dictionary[titleKey]);
        }

        document.querySelectorAll("[data-language-choice]").forEach(button => {
            button.classList.toggle("is-selected", button.dataset.languageChoice === selected);
            button.setAttribute("aria-pressed", String(button.dataset.languageChoice === selected));
        });

        window.dispatchEvent(new CustomEvent("pharmaflow:language-changed", {
            detail: { language: selected }
        }));
    };

    window.pharmaFlowLanguage = {
        apply: applyLanguage,
        get: () => localStorage.getItem("pharmaflow-language") || "en"
    };

    document.addEventListener("DOMContentLoaded", () => {
        applyLanguage(localStorage.getItem("pharmaflow-language") || "en");
    });
