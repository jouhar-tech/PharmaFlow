-- Native Firebase Cloud Messaging registrations for Median Android/iOS app installs.
-- Run this once against the PharmaHex production Supabase PostgreSQL database.

CREATE TABLE IF NOT EXISTS public.fcm_device_tokens (
    device_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    token TEXT NOT NULL,
    platform VARCHAR(12) NOT NULL CHECK (platform IN ('android', 'ios')),
    user_agent TEXT NULL,
    permission_granted BOOLEAN NOT NULL DEFAULT TRUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_success_at TIMESTAMPTZ NULL,
    last_failure_at TIMESTAMPTZ NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS fcm_device_tokens_token_unique_idx
    ON public.fcm_device_tokens(token);

CREATE INDEX IF NOT EXISTS fcm_device_tokens_profile_active_idx
    ON public.fcm_device_tokens(profile_id, is_active);


-- Device registration tokens are sensitive identifiers. Keep them inaccessible
-- through Supabase's public Data API; PharmaHex accesses this table server-side.
ALTER TABLE public.fcm_device_tokens ENABLE ROW LEVEL SECURITY;
