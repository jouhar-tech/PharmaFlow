-- PharmaFlow: persistent 14-day sliding sessions for the Render deployment.
-- Run this once in Supabase SQL Editor on the PharmaFlow-Production project
-- BEFORE deploying the persistent-session code.
--
-- The ASP.NET Core Data Protection key ring is stored in this private schema
-- so Render container restarts do not invalidate the session cookie.
-- The Postgres IDistributedCache provider creates pharmaflow_private.session_cache
-- automatically at application startup (CreateIfNotExists = true).

CREATE SCHEMA IF NOT EXISTS pharmaflow_private AUTHORIZATION postgres;

REVOKE ALL ON SCHEMA pharmaflow_private FROM PUBLIC;
REVOKE ALL ON SCHEMA pharmaflow_private FROM anon, authenticated, service_role;
GRANT USAGE, CREATE ON SCHEMA pharmaflow_private TO postgres;

CREATE TABLE IF NOT EXISTS pharmaflow_private."DataProtectionKeys"
(
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "FriendlyName" text NOT NULL,
    "Xml" text NULL
);

REVOKE ALL ON TABLE pharmaflow_private."DataProtectionKeys" FROM PUBLIC;
REVOKE ALL ON TABLE pharmaflow_private."DataProtectionKeys" FROM anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE pharmaflow_private."DataProtectionKeys" TO postgres;

